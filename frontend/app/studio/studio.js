/* ---------- Storage (saved in the browser so patients persist) ---------- */
const STORAGE_KEY = "twinverse.studio";

export function loadDb() {
  let db = { patients: [], currentId: null };
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) db = JSON.parse(raw);
  } catch (e) {
    /* ignore */
  }
  if (!db.patients || !db.patients.length) {
    const s = samplePatient();
    db = { patients: [s], currentId: s.id };
  }
  if (!db.patients.some((p) => p.id === db.currentId)) {
    db.currentId = db.patients[0].id;
  }
  return db;
}

export function saveDb(db) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(db));
  } catch (e) {
    /* storage unavailable: keep working in memory */
  }
}

/* =====================================================================
   CONSISTENCY CHECKS
   Rule-based stand-in. The real system adds an LLM pass that cross-checks
   history, medications, labs and artifacts for contradictions.
   ===================================================================== */
export function runChecks(p) {
  const errors = [];
  const warnings = [];
  if (!p.name.trim()) errors.push("Add the patient's name.");
  if (!String(p.age).trim()) errors.push("Add the patient's age.");
  if (!p.objectives.some((o) => o.trim()))
    errors.push("Add at least one learning objective. Student feedback is built from these.");
  if (!p.facts.length) errors.push("Add clinical facts for the student to discover.");

  p.facts.forEach((f, i) => {
    const n = f.label.trim() || "Fact " + (i + 1);
    if (!f.label.trim() || !f.value.trim())
      errors.push(`"${n}" needs both a label and a value.`);
    if (!f.triggers.length)
      errors.push(`"${n}" has no release words, so students can never unlock it.`);
  });

  p.artifacts.forEach((a, i) => {
    const n = a.name.trim() || "Artifact " + (i + 1);
    if (!a.name.trim()) errors.push(`Artifact ${i + 1} needs a name.`);
    if (!a.finding.trim())
      errors.push(`"${n}" needs a finding summary. The patient and feedback rely on it.`);
    if (!a.triggers.length)
      errors.push(`"${n}" has no release words, so students can never see it.`);
    if (!a.fileName)
      warnings.push(`"${n}" has no file attached. Students will see the finding text only.`);
    const f = a.finding.toLowerCase();
    if (a.abnormal && /\bnormal\b|unremarkable|within normal/.test(f) && !/abnormal/.test(f))
      warnings.push(`"${n}" is marked abnormal, but its finding reads as normal.`);
    if (!a.abnormal && /elevat|depress|abnormal|infiltrate|fracture|mass|effusion|occlu/.test(f))
      warnings.push(`"${n}" is not marked abnormal, but its finding describes an abnormality.`);
  });

  const textOf = (fn) =>
    p.facts
      .filter(fn)
      .map((f) => (f.label + " " + f.value).toLowerCase())
      .join(" ");
  const medsText = textOf((f) => f.tab === "meds" && !/allerg/i.test(f.label));
  const historyText = textOf((f) => f.tab === "history" || f.tab === "summary");
  const rules = [
    [/statin/, /cholesterol|lipid|coronary|cardiovascular|heart|stroke/, "a statin is listed, but no matching condition (cholesterol or heart disease) appears in the history"],
    [/pril|sartan|amlodipine|metoprolol|hydrochlorothiazide/, /hypertension|blood pressure|heart failure|kidney|heart|angina/, "a blood pressure medicine is listed, but no matching condition appears in the history"],
    [/metformin|insulin|glipizide/, /diabet/, "a diabetes medicine is listed, but diabetes is not in the history"],
    [/levothyroxine/, /thyroid/, "levothyroxine is listed, but thyroid disease is not in the history"],
    [/inhaler|albuterol|salbutamol/, /asthma|copd|emphysema|bronch/, "an inhaler is listed, but no lung condition appears in the history"],
  ];
  rules.forEach(([drug, cond, msg]) => {
    if (drug.test(medsText) && !cond.test(historyText))
      warnings.push("Consistency: " + msg + ".");
  });

  if (!p.facts.some((f) => /allerg/i.test(f.label)))
    warnings.push('No allergies recorded. If there are none, add a fact saying "No known allergies".');
  if (!p.facts.some((f) => f.key))
    warnings.push("No facts are marked as key findings, so feedback cannot score what the student missed.");
  if (!p.sources.length)
    warnings.push("No knowledge sources attached. The patient will rely only on the facts above.");

  const seen = {};
  const everything = p.facts
    .map((f) => [f.label || "Fact", f.triggers])
    .concat(p.artifacts.map((a) => [a.name || "Artifact", a.triggers]));
  everything.forEach(([label, words]) =>
    words.forEach((w) => {
      (seen[w] = seen[w] || []).push(label);
    })
  );
  Object.entries(seen).forEach(([w, labels]) => {
    if (labels.length > 1)
      warnings.push(`The release word "${w}" unlocks several items at once: ${labels.join(", ")}.`);
  });

  return { errors, warnings };
}

/* The object below is what the Encounter screen loads as its PATIENT.
   Note: facts and artifacts carry no written reply. The patient's spoken
   line is generated by the AI from the chart value at encounter time. */
export function toEncounterProfile(p) {
  const facts = [
    {
      id: "demo",
      tab: "summary",
      label: "Patient",
      value: `${p.name}, ${p.age}-year-old ${p.sex.toLowerCase()}`,
      start: true,
    },
  ];
  p.facts.forEach((f) =>
    facts.push({
      id: f.id,
      tab: f.tab,
      label: f.label,
      value: f.value,
      key: f.key,
      triggers: f.triggers,
    })
  );
  p.artifacts.forEach((a) =>
    facts.push({
      id: a.id,
      tab: a.type === "Lab report" ? "labs" : "artifacts",
      label: a.name,
      value: a.finding,
      flag: a.abnormal ? "Abnormal" : undefined,
      artifact: a.type === "ECG" ? "ecg" : undefined,
      fileName: a.fileName || undefined,
      triggers: a.triggers,
    })
  );
  return {
    name: p.name,
    age: Number(p.age),
    sex: p.sex,
    greeting: p.greeting,
    fallback: "I'm not sure what you mean. Could you ask me another way?",
    tabs: [
      { id: "summary", label: "Summary" },
      { id: "history", label: "History" },
      { id: "meds", label: "Meds & allergies" },
      { id: "labs", label: "Labs" },
      { id: "artifacts", label: "ECG & imaging" },
      { id: "log", label: "Disclosure log" },
    ],
    facts,
    objectives: p.objectives.filter((o) => o.trim()),
    sources: p.sources.map((s) => ({ title: s.title, note: s.note })),
  };
}

export function downloadProfile(p) {
  const blob = new Blob([JSON.stringify(toEncounterProfile(p), null, 2)], {
    type: "application/json",
  });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = (p.name || "patient").toLowerCase().replace(/\s+/g, "-") + ".json";
  document.body.append(a);
  a.click();
  a.remove();
}
